import React, { useEffect, useState } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { 
  BookmarkCheck, 
  Trash2, 
  MapPin, 
  Clock, 
  IndianRupee, 
  ArrowRight, 
  Calendar,
  Sparkles,
  Download,
  RefreshCw,
  Eye,
  AlertCircle
} from 'lucide-react';
import { useTrip } from '../context/TripContext';

// Helper to reliably extract flat destination list from any trip format
const extractTripDestinations = (trip) => {
  if (Array.isArray(trip.destinations) && trip.destinations.length > 0) {
    return trip.destinations;
  }
  
  const dests = [];
  const days = Array.isArray(trip.itinerary) 
    ? trip.itinerary 
    : (trip.itinerary?.days || []);

  for (const day of days) {
    if (day.morning?.destination) dests.push(day.morning.destination);
    if (day.afternoon?.destination) dests.push(day.afternoon.destination);
    if (day.evening?.destination) dests.push(day.evening.destination);
  }
  return dests;
};

export default function MyTripsPage() {
  const { token, user, savedTrips, loadingTrips, fetchUserTrips, deleteSavedTrip } = useTrip();
  const navigate = useNavigate();
  const [deletingId, setDeletingId] = useState(null);
  const [refreshing, setRefreshing] = useState(false);

  useEffect(() => {
    if (token) {
      fetchUserTrips();
    }
  }, [token]);

  const handleRefresh = async () => {
    setRefreshing(true);
    if (token) {
      await fetchUserTrips();
    }
    setRefreshing(false);
  };

  const handleDelete = async (tripId) => {
    if (!window.confirm('Are you sure you want to delete this saved itinerary?')) return;
    try {
      setDeletingId(tripId);
      await deleteSavedTrip(tripId);
    } catch (err) {
      alert('Could not delete trip. Please try again.');
    } finally {
      setDeletingId(null);
    }
  };

  const handleOpenItinerary = (trip) => {
    // If trip has days format, construct complete itinerary object for ItineraryPage
    const days = Array.isArray(trip.itinerary) 
      ? trip.itinerary 
      : (trip.itinerary?.days || []);

    const itineraryPayload = {
      title: trip.title,
      duration_days: trip.duration_days || (days.length || 1),
      starting_state: trip.starting_state || 'India',
      starting_city: trip.starting_city || 'Multi-city',
      companion_type: trip.companion_type || 'Traveler',
      travel_month_or_season: trip.travel_month_or_season || 'All Year',
      financials: {
        total_budget: trip.total_budget || 0,
        estimated_accommodation: trip.estimated_accommodation || 0,
        estimated_food: trip.estimated_food || 0,
        estimated_transport: trip.estimated_transport || 0,
        estimated_entrance_fees: trip.estimated_entrance_fees || 0,
        total_estimated_cost: trip.total_estimated_cost || 0,
        remaining_budget: trip.remaining_budget || 0,
        is_budget_sufficient: trip.is_budget_sufficient ?? true,
        disclaimer: 'Estimated figures calculated based on real dataset entrance fees and regional standard accommodations.'
      },
      days: days
    };

    navigate('/itinerary', { state: { itinerary: itineraryPayload } });
  };

  const handleExportText = (trip) => {
    const dests = extractTripDestinations(trip);
    const dateFormatted = trip.created_at || trip.createdAt ? new Date(trip.created_at || trip.createdAt).toLocaleDateString() : 'N/A';
    
    const lines = [
      `TRAVEL MATE - SAVED ITINERARY: ${trip.title.toUpperCase()}`,
      `Created: ${dateFormatted} | Duration: ${trip.duration_days || 1} Days`,
      `Total Projected Cost: Rs. ${(trip.total_estimated_cost || trip.totalFee || 0).toLocaleString()}`,
      `Budget Allocated: Rs. ${(trip.total_budget || 0).toLocaleString()}`,
      `------------------------------------------------------------------`,
      `DESTINATIONS INCLUDED (${dests.length} Total):`,
      ...dests.map((d, i) => 
        `${i + 1}. ${d.name} (${d.city}, ${d.state})\n   - Category: ${d.type} | Rating: ${d.rating}★\n   - Entry Fee: Rs.${d.entrance_fee_inr} | Visiting Time: ${d.time_needed_hours || 2}h`
      ),
      `------------------------------------------------------------------`,
      `Generated by Travel Mate - Popularity-Ranked Tourism Engine`
    ];

    const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${trip.title.toLowerCase().replace(/\s+/g, '_')}_itinerary.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-10">
      
      {/* Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-emerald-50 border border-emerald-200 text-emerald-800 text-xs font-bold mb-2">
            <BookmarkCheck className="w-4 h-4 text-emerald-600" />
            <span>Saved Itineraries</span>
          </div>
          <h1 className="text-3xl sm:text-4xl font-black text-slate-900 tracking-tight">
            My Saved Trips
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 mt-1 max-w-2xl">
            {token 
              ? 'Stored permanently in the SQLite database under your account profile.' 
              : 'Stored in your current local browser session. Sign in to sync across devices.'}
          </p>
        </div>

        <div className="flex items-center gap-3">
          <button
            onClick={handleRefresh}
            disabled={refreshing || loadingTrips}
            className="inline-flex items-center gap-2 px-3.5 py-2 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold transition-colors shadow-2xs"
            title="Refresh saved trips"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${refreshing || loadingTrips ? 'animate-spin text-sky-600' : 'text-slate-400'}`} />
            <span>Refresh</span>
          </button>

          <Link
            to="/preferences"
            className="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-sky-600 hover:bg-sky-700 text-white text-xs font-bold transition-colors shadow-xs"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>Plan New Itinerary</span>
          </Link>
        </div>
      </div>

      {/* Main Content Area */}
      {loadingTrips ? (
        <div className="py-20 text-center bg-white rounded-3xl border border-slate-200/80 shadow-xs space-y-3">
          <Sparkles className="w-8 h-8 text-sky-600 animate-spin mx-auto" />
          <p className="text-xs font-medium text-slate-500">Loading your saved trips...</p>
        </div>
      ) : savedTrips.length === 0 ? (
        <div className="text-center py-20 bg-white rounded-3xl border border-slate-200 p-8 max-w-lg mx-auto shadow-xs space-y-4">
          <div className="w-16 h-16 rounded-2xl bg-emerald-50 text-emerald-600 flex items-center justify-center mx-auto">
            <BookmarkCheck className="w-8 h-8" />
          </div>
          <h2 className="text-lg font-bold text-slate-900">No saved trips found</h2>
          <p className="text-xs text-slate-500 leading-relaxed">
            You haven't saved any travel itineraries yet. Generate a personalized day-wise itinerary or use the interactive trip planner to organize your journey.
          </p>
          <div className="flex flex-wrap items-center justify-center gap-3 pt-2">
            <Link
              to="/preferences"
              className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-sky-600 hover:bg-sky-700 text-white text-xs font-bold transition-all shadow-xs"
            >
              <Sparkles className="w-4 h-4" />
              <span>Personalized AI Planner</span>
            </Link>
            <Link
              to="/planner"
              className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl border border-slate-200 hover:bg-slate-50 text-slate-700 text-xs font-bold transition-all"
            >
              <span>Manual Trip Planner</span>
              <ArrowRight className="w-4 h-4" />
            </Link>
          </div>
        </div>
      ) : (
        <div className="space-y-6">
          {savedTrips.map((trip) => {
            const dests = extractTripDestinations(trip);
            const dateStr = trip.created_at || trip.createdAt;
            const formattedDate = dateStr ? new Date(dateStr).toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' }) : 'Recent';
            const totalCost = trip.total_estimated_cost ?? trip.totalFee ?? 0;
            const totalBudget = trip.total_budget ?? 0;

            return (
              <div
                key={trip.id}
                className="bg-white rounded-3xl border border-slate-200/80 p-6 sm:p-8 shadow-xs space-y-5 hover:border-slate-300 hover:shadow-md transition-all"
              >
                {/* Trip Card Top Bar */}
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-5 border-b border-slate-100">
                  <div className="space-y-1">
                    <div className="flex items-center gap-2">
                      <span className="px-2.5 py-0.5 rounded-full bg-sky-50 text-sky-700 font-bold text-[10px]">
                        {trip.duration_days || Math.max(1, Math.ceil(dests.length / 3))} Days
                      </span>
                      {trip.is_budget_sufficient === false && (
                        <span className="px-2.5 py-0.5 rounded-full bg-amber-50 text-amber-700 font-bold text-[10px] flex items-center gap-1">
                          <AlertCircle className="w-3 h-3" />
                          <span>Exceeds Budget</span>
                        </span>
                      )}
                    </div>
                    <h3 className="text-xl font-bold text-slate-900 tracking-tight">
                      {trip.title}
                    </h3>
                    <p className="text-xs text-slate-400 flex items-center gap-2">
                      <Calendar className="w-3.5 h-3.5" />
                      <span>Saved on {formattedDate}</span>
                      <span>•</span>
                      <span>{dests.length} Attractions scheduled</span>
                    </p>
                  </div>

                  {/* Financial Pillars & Quick Actions */}
                  <div className="flex flex-wrap items-center gap-3">
                    <div className="text-right sm:pr-4 sm:border-r sm:border-slate-100">
                      <span className="text-[10px] text-slate-400 block font-medium">Est. Trip Cost</span>
                      <span className="font-extrabold text-base text-slate-800">
                        ₹{Number(totalCost).toLocaleString()}
                      </span>
                      {totalBudget > 0 && (
                        <span className="text-[10px] text-slate-500 block">
                          Budget: ₹{Number(totalBudget).toLocaleString()}
                        </span>
                      )}
                    </div>

                    <button
                      onClick={() => handleOpenItinerary(trip)}
                      className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-sky-50 hover:bg-sky-100 text-sky-700 text-xs font-bold transition-colors"
                      title="Inspect complete day-wise schedule"
                    >
                      <Eye className="w-3.5 h-3.5" />
                      <span>View Schedule</span>
                    </button>

                    <button
                      onClick={() => handleExportText(trip)}
                      className="p-2 text-slate-400 hover:text-slate-700 hover:bg-slate-100 rounded-xl transition-colors"
                      title="Export text itinerary"
                    >
                      <Download className="w-4 h-4" />
                    </button>

                    <button
                      onClick={() => handleDelete(trip.id)}
                      disabled={deletingId === trip.id}
                      className="p-2 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-xl transition-colors"
                      title="Delete trip"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>
                </div>

                {/* Destinations Grid Preview */}
                {dests.length > 0 ? (
                  <div className="space-y-2">
                    <p className="text-xs font-bold text-slate-700">Planned Sightseeing Destinations:</p>
                    <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-3">
                      {dests.map((d, idx) => (
                        <Link
                          key={d.id ? `${d.id}-${idx}` : idx}
                          to={d.id ? `/destinations/${d.id}` : '#'}
                          className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100 hover:border-sky-300 hover:bg-sky-50/50 transition-all text-xs block group"
                        >
                          <div className="flex items-center justify-between text-[10px] text-slate-400 mb-1">
                            <span className="font-bold text-sky-600 group-hover:text-sky-700">Slot #{idx + 1}</span>
                            <span className="font-semibold truncate max-w-[120px]">{d.type}</span>
                          </div>
                          <p className="font-bold text-slate-900 truncate group-hover:text-sky-900">{d.name}</p>
                          <p className="text-[11px] text-slate-500 truncate mt-0.5">{d.city}, {d.state}</p>
                          <div className="flex items-center justify-between text-[10px] text-slate-400 mt-2 pt-1.5 border-t border-slate-200/50">
                            <span>Rating: <strong className="text-slate-700">{d.rating || d.google_review_rating || '4.5'}★</strong></span>
                            <span>Fee: <strong className="text-slate-700">₹{d.entrance_fee_inr || 0}</strong></span>
                          </div>
                        </Link>
                      ))}
                    </div>
                  </div>
                ) : (
                  <p className="text-xs text-slate-400 italic">No specific attractions attached to this route.</p>
                )}
              </div>
            );
          })}
        </div>
      )}

    </div>
  );
}
